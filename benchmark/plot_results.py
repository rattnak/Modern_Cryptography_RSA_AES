"""
Plot benchmark results generated by the `benchmark` scripts.

Usage examples (from project root):
  # plot a single results file and save PNG
  python benchmark/plot_results.py --input benchmark/results_aes_2025....json --out benchmark/plots

  # plot all results files in `benchmark/` and save separate PNGs
  python benchmark/plot_results.py --input benchmark/ --out benchmark/plots

  # show plots interactively (requires GUI)
  python benchmark/plot_results.py --input benchmark/ --show

This script depends only on the stdlib and matplotlib (for plotting).
Install matplotlib if needed:
  pip install matplotlib
"""
from __future__ import annotations
import argparse
import json
import math
import os
from pathlib import Path
from typing import Dict, List

import matplotlib.pyplot as plt


def find_result_files(path: Path) -> List[Path]:
    if path.is_file():
        return [path]
    files = []
    for p in path.glob('results_*.json'):
        files.append(p)
    for p in path.glob('*.json'):
        # accept direct JSONs too
        if p not in files:
            files.append(p)
    return sorted(files)


def load_json(p: Path) -> Dict:
    with p.open('r', encoding='utf-8') as fh:
        return json.load(fh)


def extract_metrics(data: Dict) -> Dict:
    """Return a dictionary summarizing metrics per size.

    Format returned:
    {
      'sizes': [128,192,...],
      'keygen_mean': [...],
      'keygen_std': [...],
      'encrypt_mean': [...],
      'encrypt_std': [...],
      'decrypt_mean': [...],
      'decrypt_std': [...],
    }
    """
    sizes = []
    kg_mean = []
    kg_std = []
    enc_mean = []
    enc_std = []
    dec_mean = []
    dec_std = []

    for bench in data.get('benchmarks', []):
        # bench may have 'keygen' and 'io' fields
        keygen = bench.get('keygen', {})
        io = bench.get('io', {})

        size = bench.get('size') or keygen.get('size') or io.get('size')
        # Fallback: try top-level sizes list order
        if size is None and 'sizes' in data:
            # best-effort: use corresponding index
            idx = len(sizes)
            try:
                size = data['sizes'][idx]
            except Exception:
                size = idx

        sizes.append(size)

        kg_mean.append(keygen.get('time_mean') or _safe_mean(keygen.get('times')))
        kg_std.append(keygen.get('time_std') or _safe_std(keygen.get('times')))

        enc_mean.append(io.get('encrypt_mean') or _safe_mean(io.get('encrypt_times')))
        enc_std.append(io.get('encrypt_std') or _safe_std(io.get('encrypt_times')))

        dec_mean.append(io.get('decrypt_mean') or _safe_mean(io.get('decrypt_times')))
        dec_std.append(io.get('decrypt_std') or _safe_std(io.get('decrypt_times')))

    return {
        'sizes': sizes,
        'keygen_mean': kg_mean,
        'keygen_std': kg_std,
        'encrypt_mean': enc_mean,
        'encrypt_std': enc_std,
        'decrypt_mean': dec_mean,
        'decrypt_std': dec_std,
    }


def _safe_mean(lst):
    try:
        if not lst:
            return None
        return sum(lst) / len(lst)
    except Exception:
        return None


def _safe_std(lst):
    try:
        if not lst or len(lst) == 1:
            return 0.0
        m = sum(lst) / len(lst)
        var = sum((x - m) ** 2 for x in lst) / len(lst)
        return math.sqrt(var)
    except Exception:
        return 0.0


def plot_single(metrics: Dict, title: str, out_path: Path | None = None, show: bool = False):
    sizes = metrics['sizes']
    # normalize sizes to strings for x-axis
    labels = [str(s) for s in sizes]

    # Create 2 subplots: keygen and IO
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    # Keygen plot
    axes[0].errorbar(labels, metrics['keygen_mean'], yerr=metrics['keygen_std'], marker='o', capsize=5)
    axes[0].set_title('Key Generation Time')
    axes[0].set_xlabel('Key size (bits)')
    axes[0].set_ylabel('Time (s)')

    # IO plot (encrypt/decrypt)
    axes[1].errorbar(labels, metrics['encrypt_mean'], yerr=metrics['encrypt_std'], marker='o', capsize=5, label='encrypt')
    axes[1].errorbar(labels, metrics['decrypt_mean'], yerr=metrics['decrypt_std'], marker='o', capsize=5, label='decrypt')
    axes[1].set_title('Encrypt / Decrypt Time')
    axes[1].set_xlabel('Key size (bits)')
    axes[1].set_ylabel('Time (s)')
    axes[1].legend()

    fig.suptitle(title)
    fig.tight_layout(rect=[0, 0.03, 1, 0.95])

    if out_path:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(out_path, dpi=150)
        print(f'Saved plot: {out_path}')
    if show:
        plt.show()
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description='Plot benchmark JSON results')
    parser.add_argument('--input', '-i', required=True, help='Input file or directory containing results_*.json')
    parser.add_argument('--out', '-o', default='benchmark/plots', help='Output directory to save plots (PNG)')
    parser.add_argument('--show', action='store_true', help='Show plots interactively')
    parser.add_argument('--aggregate', action='store_true', help='Aggregate multiple files into a single averaged plot')
    args = parser.parse_args()

    p = Path(args.input)
    files = find_result_files(p)
    if not files:
        print('No result JSON files found at', p)
        return

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.aggregate and len(files) > 1:
        # Simple aggregation: average the means for each size across files
        accum: Dict[int, Dict[str, List[float]]] = {}
        for f in files:
            data = load_json(f)
            metrics = extract_metrics(data)
            for i, size in enumerate(metrics['sizes']):
                entry = accum.setdefault(size, {'kg': [], 'kg_s': [], 'enc': [], 'enc_s': [], 'dec': [], 'dec_s': []})
                if metrics['keygen_mean'][i] is not None:
                    entry['kg'].append(metrics['keygen_mean'][i])
                    entry['kg_s'].append(metrics['keygen_std'][i] or 0.0)
                entry['enc'].append(metrics['encrypt_mean'][i])
                entry['enc_s'].append(metrics['encrypt_std'][i] or 0.0)
                entry['dec'].append(metrics['decrypt_mean'][i])
                entry['dec_s'].append(metrics['decrypt_std'][i] or 0.0)

        sizes_sorted = sorted(accum.keys())
        metrics_agg = {
            'sizes': sizes_sorted,
            'keygen_mean': [sum(accum[s]['kg']) / len(accum[s]['kg']) if accum[s]['kg'] else None for s in sizes_sorted],
            'keygen_std': [sum(accum[s]['kg_s']) / len(accum[s]['kg_s']) if accum[s]['kg_s'] else 0.0 for s in sizes_sorted],
            'encrypt_mean': [sum(accum[s]['enc']) / len(accum[s]['enc']) for s in sizes_sorted],
            'encrypt_std': [sum(accum[s]['enc_s']) / len(accum[s]['enc_s']) for s in sizes_sorted],
            'decrypt_mean': [sum(accum[s]['dec']) / len(accum[s]['dec']) for s in sizes_sorted],
            'decrypt_std': [sum(accum[s]['dec_s']) / len(accum[s]['dec_s']) for s in sizes_sorted],
        }
        out_path = out_dir / 'plot_aggregated.png'
        plot_single(metrics_agg, title='Aggregated Benchmark Results', out_path=out_path, show=args.show)
        return

    # otherwise, create one plot per file
    for f in files:
        data = load_json(f)
        metrics = extract_metrics(data)
        base = f.stem
        out_path = out_dir / f'plot_{base}.png'
        title = f'Benchmark: {f.name}'
        plot_single(metrics, title=title, out_path=out_path, show=args.show)


if __name__ == '__main__':
    main()
